PAD_TOKEN = 0

BOS_TOKEN = 1

EOS_TOKEN = 2

TEXT_PAD = 0

TEXT_BOS = 1


# =====================================================================
# STEP 1 — SYNTHETIC MULTI-SPEAKER DATASET
# =====================================================================

class SyntheticSpeechDataset(Dataset):

    """
    Creates paired text-token and speech-token sequences.

    Each speaker has a different synthetic token distribution.

    This controlled dataset allows us to test whether the model
    learns speaker-conditioned token prediction.
    """

    def __init__(
        self,
        num_samples
    ):

        self.samples = []

        for _ in range(num_samples):

            speaker_id = random.randint(
                0,
                NUM_SPEAKERS - 1
            )

            text = np.random.randint(
                3,
                TEXT_VOCAB_SIZE,
                size=TEXT_LENGTH
            )

            # Each speaker has a characteristic token range.
            speaker_start = 10 + speaker_id * 55

            speaker_end = min(
                speaker_start + 55,
                SPEECH_VOCAB_SIZE
            )

            speech = np.random.randint(
                speaker_start,
                speaker_end,
                size=SPEECH_LENGTH - 1
            )

            # Introduce weak linguistic conditioning.
            # This is only a synthetic demonstration.
            for i in range(
                len(speech)
            ):

                text_token = text[
                    i % TEXT_LENGTH
                ]

                speech[i] = (
                    speech[i] + text_token
                ) % (
                    speaker_end - speaker_start
                ) + speaker_start

            speech = np.concatenate(
                [
                    [BOS_TOKEN],
                    speech
                ]
            )

            self.samples.append(
                (
                    text.astype(np.int64),
                    speech.astype(np.int64),
                    speaker_id
                )
            )

    def __len__(self):

        return len(self.samples)

    def __getitem__(self, index):

        text, speech, speaker = self.samples[index]

        return (
            torch.tensor(
                text,
                dtype=torch.long
            ),
            torch.tensor(
                speech,
                dtype=torch.long
            ),
            torch.tensor(
                speaker,
                dtype=torch.long
            )
        )


# =====================================================================
# STEP 2 — TEXT EMBEDDING
# =====================================================================

class TextEncoder(nn.Module):

    """
    Converts discrete text tokens into continuous representations.

    In a real system this would be replaced by a suitable
    phoneme or linguistic encoder.
    """

    def __init__(self):

        super().__init__()

        self.embedding = nn.Embedding(
            TEXT_VOCAB_SIZE,
            EMBED_DIM
        )

        self.position = nn.Parameter(
            torch.randn(
                1,
                TEXT_LENGTH,
                EMBED_DIM
            ) * 0.02
        )

        self.norm = nn.LayerNorm(
            EMBED_DIM
        )

    def forward(self, text):

        x = self.embedding(text)

        x = x + self.position[:, :text.size(1)]

        return self.norm(x)


# =====================================================================
# STEP 3 — SPEAKER EMBEDDING
# =====================================================================

class SpeakerEncoder(nn.Module):

    """
    Educational speaker identity embedding.

    In production, use the trained ECAPA-TDNN encoder from Lesson 49.

    Here, speaker IDs are used to demonstrate conditioning.
    """

    def __init__(self):

        super().__init__()

        self.embedding = nn.Embedding(
            NUM_SPEAKERS,
            192
        )

        self.projection = nn.Sequential(

            nn.Linear(
                192,
                EMBED_DIM
            ),

            nn.LayerNorm(
                EMBED_DIM
            )

        )

    def forward(self, speaker_ids):

        x = self.embedding(
            speaker_ids
        )

        return self.projection(x)


# =====================================================================
# STEP 4 — CONDITIONAL FUSION
# =====================================================================

class ConditionalFusion(nn.Module):

    """
    Combines linguistic and speaker identity information.

    Speaker information is broadcast over the text sequence.
    """

    def __init__(self):

        super().__init__()

        self.fusion = nn.Sequential(

            nn.Linear(
                EMBED_DIM * 2,
                EMBED_DIM
            ),

            nn.GELU(),

            nn.LayerNorm(
                EMBED_DIM
            )

        )

    def forward(
        self,
        text_features,
        speaker_features
    ):

        speaker_features = speaker_features.unsqueeze(
            1
        )

        speaker_features = speaker_features.expand(
            -1,
            text_features.size(1),
            -1
        )

        combined = torch.cat(
            [
                text_features,
                speaker_features
            ],
            dim=-1
        )

        return self.fusion(
            combined
        )


# =====================================================================
# STEP 5 — CAUSAL SELF-ATTENTION
# =====================================================================

class CausalSelfAttention(nn.Module):

    def __init__(self):

        super().__init__()

        assert EMBED_DIM % NUM_HEADS == 0

        self.head_dim = (
            EMBED_DIM // NUM_HEADS
        )

        self.qkv = nn.Linear(
            EMBED_DIM,
            EMBED_DIM * 3
        )

        self.output = nn.Linear(
            EMBED_DIM,
            EMBED_DIM
        )

        self.dropout = nn.Dropout(
            DROPOUT
        )

    def forward(self, x):

        batch, length, channels = x.shape

        qkv = self.qkv(x)

        qkv = qkv.reshape(
            batch,
            length,
            3,
            NUM_HEADS,
            self.head_dim
        )

        qkv = qkv.permute(
            2,
            0,
            3,
            1,
            4
        )

        q, k, v = qkv.unbind(
            dim=0
        )

        # Scaled dot-product causal attention.
        output = F.scaled_dot_product_attention(
            q,
            k,
            v,
            dropout_p=(
                DROPOUT if self.training else 0.0
            ),
            is_causal=True
        )

        output = output.transpose(
            1,
            2
        ).reshape(
            batch,
            length,
            channels
        )

        return self.dropout(
            self.output(output)
        )


# =====================================================================
# STEP 6 — FEED FORWARD NETWORK
# =====================================================================

class FeedForward(nn.Module):

    def __init__(self):

        super().__init__()

        self.net = nn.Sequential(

            nn.Linear(
                EMBED_DIM,
                FFN_DIM
            ),

            nn.GELU(),

            nn.Linear(
                FFN_DIM,
                EMBED_DIM
            ),

            nn.Dropout(
                DROPOUT
            )

        )

    def forward(self, x):

        return self.net(x)


# =====================================================================
# STEP 7 — TRANSFORMER BLOCK
# =====================================================================

class TransformerBlock(nn.Module):

    def __init__(self):

        super().__init__()

        self.norm1 = nn.LayerNorm(
            EMBED_DIM
        )

        self.attention = CausalSelfAttention()

        self.norm2 = nn.LayerNorm(
            EMBED_DIM
        )

        self.ffn = FeedForward()

    def forward(self, x):

        x = x + self.attention(
            self.norm1(x)
        )

        x = x + self.ffn(
            self.norm2(x)
        )

        return x


# =====================================================================
# STEP 8 — SPEECH TOKEN GPT
# =====================================================================

class SpeakerConditionedGPT(nn.Module):

    def __init__(self):

        super().__init__()

        self.text_encoder = TextEncoder()

        self.speaker_encoder = SpeakerEncoder()

        self.conditioning = ConditionalFusion()

        self.speech_embedding = nn.Embedding(
            SPEECH_VOCAB_SIZE,
            EMBED_DIM
        )

        self.position = nn.Parameter(
            torch.randn(
                1,
                SPEECH_LENGTH,
                EMBED_DIM
            ) * 0.02
        )

        self.blocks = nn.ModuleList(
            [
                TransformerBlock()
                for _ in range(NUM_LAYERS)
            ]
        )

        self.norm = nn.LayerNorm(
            EMBED_DIM
        )

        self.output = nn.Linear(
            EMBED_DIM,
            SPEECH_VOCAB_SIZE
        )

    def forward(
        self,
        text,
        speech_input,
        speaker_ids
    ):

        text_features = self.text_encoder(
            text
        )

        speaker_features = self.speaker_encoder(
            speaker_ids
        )

        condition = self.conditioning(
            text_features,
            speaker_features
        )

        # Pool text condition to create a global linguistic context.
        global_condition = condition.mean(
            dim=1,
            keepdim=True
        )

        speech_features = self.speech_embedding(
            speech_input
        )

        length = speech_features.size(1)

        speech_features = (
            speech_features
            + self.position[:, :length]
            + global_condition
        )

        for block in self.blocks:

            speech_features = block(
                speech_features
            )

        speech_features = self.norm(
            speech_features
        )

        logits = self.output(
            speech_features
        )

        return logits


# =====================================================================
# STEP 9 — TRAINING
# =====================================================================

def train_model(
    model,
    train_loader,
    val_loader
):

    optimizer = torch.optim.AdamW(
        model.parameters(),
        lr=LEARNING_RATE,
        weight_decay=0.01
    )

    scheduler = torch.optim.lr_scheduler.CosineAnnealingLR(
        optimizer,
        T_max=EPOCHS
    )

    history = {
        "train": [],
        "validation": []
    }

    best_val = float("inf")

    for epoch in range(EPOCHS):

        model.train()

        train_losses = []

        for text, speech, speaker in train_loader:

            text = text.to(DEVICE)

            speech = speech.to(DEVICE)

            speaker = speaker.to(DEVICE)

            # Teacher forcing:
            # Input: BOS, token_1, ..., token_(T-1)
            # Target: token_1, ..., token_T

            speech_input = speech[:, :-1]

            speech_target = speech[:, 1:]

            logits = model(
                text,
                speech_input,
                speaker
            )

            loss = F.cross_entropy(
                logits.reshape(
                    -1,
                    SPEECH_VOCAB_SIZE
                ),
                speech_target.reshape(-1)
            )

            optimizer.zero_grad(
                set_to_none=True
            )

            loss.backward()

            torch.nn.utils.clip_grad_norm_(
                model.parameters(),
                1.0
            )

            optimizer.step()

            train_losses.append(
                loss.item()
            )

        train_loss = np.mean(
            train_losses
        )

        # -------------------------------------------------------------
        # Validation
        # -------------------------------------------------------------

        model.eval()

        val_losses = []

        with torch.no_grad():

            for text, speech, speaker in val_loader:

                text = text.to(DEVICE)

                speech = speech.to(DEVICE)

                speaker = speaker.to(DEVICE)

                logits = model(
                    text,
                    speech[:, :-1],
                    speaker
                )

                loss = F.cross_entropy(
                    logits.reshape(
                        -1,
                        SPEECH_VOCAB_SIZE
                    ),
                    speech[:, 1:].reshape(-1)
                )

                val_losses.append(
                    loss.item()
                )

        val_loss = np.mean(
            val_losses
        )

        scheduler.step()

        history["train"].append(
            float(train_loss)
        )

        history["validation"].append(
            float(val_loss)
        )

        print(
            f"Epoch {epoch + 1:03d}/{EPOCHS} | "
            f"Train: {train_loss:.4f} | "
            f"Validation: {val_loss:.4f}"
        )

        if val_loss < best_val:

            best_val = val_loss

            torch.save(
                model.state_dict(),
                os.path.join(
                    OUTPUT_DIR,
                    "lesson50_best.pt"
                )
            )

    return history


# =====================================================================
# STEP 10 — AUTOREGRESSIVE GENERATION
# =====================================================================

@torch.no_grad()
def generate_speech_tokens(
    model,
    text,
    speaker_id,
    max_tokens=50,
    temperature=0.8
):

    model.eval()

    text = torch.tensor(
        text,
        dtype=torch.long
    ).unsqueeze(0).to(DEVICE)

    speaker = torch.tensor(
        [speaker_id],
        dtype=torch.long
    ).to(DEVICE)

    generated = torch.tensor(
        [[BOS_TOKEN]],
        dtype=torch.long,
        device=DEVICE
    )

    for _ in range(max_tokens):

        logits = model(
            text,
            generated,
            speaker
        )

        next_logits = logits[
            :,
            -1,
            :
        ]

        next_logits = next_logits / max(
            temperature,
            1e-5
        )

        # Avoid generating PAD and BOS as ordinary output tokens.
        next_logits[:, PAD_TOKEN] = -float("inf")

        next_logits[:, BOS_TOKEN] = -float("inf")

        probabilities = F.softmax(
            next_logits,
            dim=-1
        )

        next_token = torch.multinomial(
            probabilities,
            num_samples=1
        )

        generated = torch.cat(
            [
                generated,
                next_token
            ],
            dim=1
        )

        if next_token.item() == EOS_TOKEN:

            break

        if generated.size(1) >= SPEECH_LENGTH:

            break

    return generated[
        0
    ].cpu().tolist()


