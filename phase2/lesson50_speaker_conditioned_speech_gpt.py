def main():

    print("=" * 72)

    print(
        "LESSON 50 — SPEAKER-CONDITIONED SPEECH TOKEN GPT"
    )

    print("=" * 72)

    print(f"\nDevice: {DEVICE}")

    print(f"Text vocabulary: {TEXT_VOCAB_SIZE}")

    print(f"Speech vocabulary: {SPEECH_VOCAB_SIZE}")

    print(f"Embedding dimension: {EMBED_DIM}")

    print(f"Transformer layers: {NUM_LAYERS}")

    # ---------------------------------------------------------------
    # Dataset
    # ---------------------------------------------------------------

    train_dataset = SyntheticSpeechDataset(
        NUM_TRAIN_SAMPLES
    )

    val_dataset = SyntheticSpeechDataset(
        NUM_VAL_SAMPLES
    )

    train_loader = DataLoader(
        train_dataset,
        batch_size=BATCH_SIZE,
        shuffle=True,
        num_workers=0
    )

    val_loader = DataLoader(
        val_dataset,
        batch_size=BATCH_SIZE,
        shuffle=False,
        num_workers=0
    )

    print(
        f"\nTraining samples: {len(train_dataset)}"
    )

    print(
        f"Validation samples: {len(val_dataset)}"
    )

    # ---------------------------------------------------------------
    # Model
    # ---------------------------------------------------------------

    model = SpeakerConditionedGPT().to(
        DEVICE
    )

    parameters = sum(
        p.numel()
        for p in model.parameters()
    )

    print(
        f"\nModel parameters: {parameters:,}"
    )

    # ---------------------------------------------------------------
    # Training
    # ---------------------------------------------------------------

    print("\nStarting training...\n")

    history = train_model(
        model,
        train_loader,
        val_loader
    )

    # ---------------------------------------------------------------
    # Load best checkpoint
    # ---------------------------------------------------------------

    model.load_state_dict(
        torch.load(
            os.path.join(
                OUTPUT_DIR,
                "lesson50_best.pt"
            ),
            map_location=DEVICE,
            weights_only=True
        )
    )

    # ---------------------------------------------------------------
    # Speaker-conditioned generation
    # ---------------------------------------------------------------

    print("\n" + "=" * 72)

    print("SPEAKER-CONDITIONED SPEECH GENERATION")

    print("=" * 72)

    example_text = np.random.randint(
        3,
        TEXT_VOCAB_SIZE,
        size=TEXT_LENGTH
    ).tolist()

    results = {}

    for speaker_id in range(
        NUM_SPEAKERS
    ):

        generated = generate_speech_tokens(
            model,
            example_text,
            speaker_id,
            max_tokens=50,
            temperature=0.8
        )

        results[speaker_id] = generated

        print(
            f"\nSpeaker {speaker_id}:"
        )

        print(
            "Generated tokens:",
            generated
        )

    # ---------------------------------------------------------------
    # Visualizations
    # ---------------------------------------------------------------

    plot_training(
        history
    )

    plot_speaker_generation(
        results
    )

    # ---------------------------------------------------------------
    # Save generated sequences
    # ---------------------------------------------------------------

    np.savez(
        os.path.join(
            OUTPUT_DIR,
            "lesson50_generated_tokens.npz"
        ),
        **{
            f"speaker_{k}": np.array(v)
            for k, v in results.items()
        }
    )

    print("\n" + "=" * 72)

    print("LESSON 50 COMPLETED")

    print("=" * 72)

    print("\nOutput directory:")

    print(OUTPUT_DIR)

    print("\nGenerated files:")

    print("  lesson50_best.pt")

    print("  lesson50_training.png")

    print("  lesson50_speaker_generation.png")

    print("  lesson50_generated_tokens.npz")


if __name__ == "__main__":

    main()