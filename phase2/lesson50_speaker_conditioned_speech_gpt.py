SEED = 50

DEVICE = "cuda" if torch.cuda.is_available() else "cpu"

NUM_SPEAKERS = 4

TEXT_VOCAB_SIZE = 128

SPEECH_VOCAB_SIZE = 256

TEXT_LENGTH = 32

SPEECH_LENGTH = 64

EMBED_DIM = 256

NUM_HEADS = 8

NUM_LAYERS = 4

FFN_DIM = 1024

DROPOUT = 0.1

BATCH_SIZE = 32

EPOCHS = 40

LEARNING_RATE = 3e-4

NUM_TRAIN_SAMPLES = 2000

NUM_VAL_SAMPLES = 300

OUTPUT_DIR = "lesson50_outputs"

os.makedirs(
    OUTPUT_DIR,
    exist_ok=True
)

random.seed(SEED)

