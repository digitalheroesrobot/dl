def load_wav(path):
    """
    Minimal WAV loader using only Python's standard library.

    Supported:

        PCM WAV
        mono or stereo
        8/16/24/32-bit PCM

    Stereo is converted to mono.

    The audio is resampled using simple linear interpolation if the
    original sample rate differs from TARGET_SAMPLE_RATE.

    This loader is intentionally simple for educational purposes.
    """

    with wave.open(path, "rb") as wav:

        sample_rate = wav.getframerate()

        channels = wav.getnchannels()

        sample_width = wav.getsampwidth()

        frame_count = wav.getnframes()

        raw = wav.readframes(frame_count)

    # --------------------------------------------------------------
    # Decode PCM
    # --------------------------------------------------------------

    if sample_width == 1:

        data = np.frombuffer(
            raw,
            dtype=np.uint8,
        ).astype(np.float32)

        data = (
            data - 128.0
        ) / 128.0

    elif sample_width == 2:

        data = np.frombuffer(
            raw,
            dtype=np.int16,
        ).astype(np.float32)

        data /= 32768.0

    elif sample_width == 3:

        raw_bytes = np.frombuffer(
            raw,
            dtype=np.uint8,
        )

        samples = []

        for i in range(
            0,
            len(raw_bytes),
            3,
        ):

            value = (
                int(raw_bytes[i])
                | (int(raw_bytes[i + 1]) << 8)
                | (int(raw_bytes[i + 2]) << 16)
            )

            if value & 0x800000:

                value -= 1 << 24

            samples.append(value)

        data = (
            np.asarray(
                samples,
                dtype=np.float32,
            )
            / 8388608.0
        )

    elif sample_width == 4:

        data = np.frombuffer(
            raw,
            dtype=np.int32,
        ).astype(np.float32)

        data /= 2147483648.0

    else:

        raise ValueError(
            f"Unsupported WAV sample width: "
            f"{sample_width} bytes"
        )

    # --------------------------------------------------------------
    # Stereo → mono
    # --------------------------------------------------------------

    if channels > 1:

        data = data.reshape(
            -1,
            channels,
        )

        data = data.mean(
            axis=1
        )

    # --------------------------------------------------------------
    # Resampling
    # --------------------------------------------------------------

    if sample_rate != TARGET_SAMPLE_RATE:

        old_length = len(data)

        new_length = int(
            round(
                old_length
                * TARGET_SAMPLE_RATE
                / sample_rate
            )
        )

        old_positions = np.linspace(
            0,
            1,
            old_length,
        )

        new_positions = np.linspace(
            0,
            1,
            new_length,
        )

        data = np.interp(
            new_positions,
            old_positions,
            data,
        )

    return data.astype(
        np.float32
    )


# ======================================================================
# SYNTHETIC SPEECH-LIKE SIGNAL
# ======================================================================

def generate_speech_like_signal(
    duration=TEST_DURATION,
    sample_rate=TARGET_SAMPLE_RATE,
):
    """
    Generate a deterministic speech-like signal.

    This is NOT actual speech.

    The goal is to provide a structured acoustic signal containing:

        fundamental frequency
        harmonics
        amplitude envelopes
        multiple pseudo-phonetic regions

    so that the encoder has a non-trivial waveform to process.
    """

    total_samples = int(
        duration * sample_rate
    )

    time = np.arange(
        total_samples,
        dtype=np.float32,
    ) / sample_rate

    # --------------------------------------------------------------
    # Slowly changing fundamental frequency
    # --------------------------------------------------------------

    f0 = (
        130.0
        + 25.0 * np.sin(
            2.0
            * np.pi
            * 1.5
            * time
        )
    )

    phase = np.cumsum(
        2.0
        * np.pi
        * f0
        / sample_rate
    )

    # --------------------------------------------------------------
    # Harmonic structure
    # --------------------------------------------------------------

    signal = (
        0.55 * np.sin(phase)
        + 0.25 * np.sin(2.0 * phase)
        + 0.12 * np.sin(3.0 * phase)
        + 0.08 * np.sin(4.0 * phase)
    )

    # --------------------------------------------------------------
    # Slowly changing amplitude envelope
    # --------------------------------------------------------------

    envelope = (
        0.65
        + 0.25
        * np.sin(
            2.0
            * np.pi
            * 2.2
            * time
        )
    )

    # --------------------------------------------------------------
    # Add several amplitude regions
    # --------------------------------------------------------------

    region_envelope = np.zeros_like(
        time
    )

    region_count = 6

    region_length = len(time) // region_count

    for i in range(region_count):

        start = i * region_length

        end = (
            (i + 1) * region_length
            if i < region_count - 1
            else len(time)
        )

        local_t = np.linspace(
            0,
            1,
            end - start,
        )

        attack = np.minimum(
            local_t / 0.12,
            1.0,
        )

        release = np.minimum(
            (1.0 - local_t) / 0.18,
            1.0,
        )

        region_envelope[
            start:end
        ] = (
            attack
            * release
        )

    signal *= envelope
    signal *= region_envelope

    # --------------------------------------------------------------
    # Add a small deterministic excitation component
    # --------------------------------------------------------------

    excitation = (
        0.015
        * np.sin(
            2.0
            * np.pi
            * 3200.0
            * time
        )
    )

    signal += excitation

    # --------------------------------------------------------------
    # Normalize
    # --------------------------------------------------------------

    peak = np.max(
        np.abs(signal)
    )

    if peak > 0:

        signal /= peak

    return signal.astype(
        np.float32
    )


# ======================================================================
# WAVEFORM PREPROCESSING
# ======================================================================

def prepare_waveform(
    waveform,
    max_duration=TEST_DURATION,
):
    """
    Convert numpy waveform into a normalized PyTorch tensor.
    """

    max_samples = int(
        max_duration
        * TARGET_SAMPLE_RATE
    )

    waveform = waveform[:max_samples]

    if len(waveform) == 0:

        raise ValueError(
            "Waveform contains no samples."
        )

    waveform = waveform.astype(
        np.float32
    )

    waveform -= waveform.mean()

    peak = np.max(
        np.abs(waveform)
    )

    if peak > 0:

        waveform /= peak

    tensor = torch.from_numpy(
        waveform
    )

    tensor = tensor.unsqueeze(0)

    tensor = tensor.unsqueeze(0)

    return tensor


# ======================================================================
# SPEECH ENCODER BLOCK
# ======================================================================

class SpeechEncoderBlock(nn.Module):
    """
    One temporal convolutional encoder block.

    Input:

        [batch, channels, time]

    Output:

        [batch, output_channels, reduced_time]

    The stride performs temporal compression.
    """

    def __init__(
        self,
        input_channels,
        output_channels,
        stride,
    ):

        super().__init__()

        self.conv = nn.Conv1d(
            input_channels,
            output_channels,
            kernel_size=KERNEL_SIZE,
            stride=stride,
            padding=KERNEL_SIZE // 2,
        )

        self.norm = nn.GroupNorm(
            num_groups=8,
            num_channels=output_channels,
        )

        self.activation = nn.GELU()

    def forward(self, x):

        x = self.conv(x)

        x = self.norm(x)

        x = self.activation(x)

        return x


# ======================================================================
# SPEECH TOKENIZER
# ======================================================================

class SpeechTokenizer(nn.Module):
    """
    Neural speech encoder.

    Pipeline:

        waveform
            ↓
        Conv1D
            ↓
        temporal compression
            ↓
        feature extraction
            ↓
        latent projection
            ↓
        continuous speech tokens

    The output is continuous.

    Vector quantization is intentionally NOT included here.
    """

    def __init__(
        self,
        latent_dim=LATENT_DIM,
    ):

        super().__init__()

        blocks = []

        input_channels = 1

        for output_channels, stride in zip(
            CHANNELS,
            STRIDES,
        ):

            blocks.append(
                SpeechEncoderBlock(
                    input_channels=input_channels,
                    output_channels=output_channels,
                    stride=stride,
                )
            )

            input_channels = output_channels

        self.encoder = nn.Sequential(
            *blocks
        )

        self.projection = nn.Conv1d(
            input_channels,
            latent_dim,
            kernel_size=1,
        )

    def forward(self, waveform):

        x = self.encoder(
            waveform
        )

        x = self.projection(
            x
        )

        # Convert:
        #
        # [B, C, T]
        #
        # to:
        #
        # [B, T, C]
        #
        # because a speech-token sequence is naturally represented
        # as:
        #
        # timestep × feature dimension

        x = x.transpose(
            1,
            2,
        )

        return x


