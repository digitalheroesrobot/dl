def analyze_latent(latent):

    x = latent.detach().cpu()

    mean = x.mean().item()

    std = x.std().item()

    minimum = x.min().item()

    maximum = x.max().item()

    rms = torch.sqrt(
        torch.mean(x ** 2)
    ).item()

    print("\n")
    print("=" * 72)
    print("LATENT REPRESENTATION STATISTICS")
    print("=" * 72)

    print(
        f"\nMean       : {mean:.6f}"
    )

    print(
        f"Std        : {std:.6f}"
    )

    print(
        f"Minimum    : {minimum:.6f}"
    )

    print(
        f"Maximum    : {maximum:.6f}"
    )

    print(
        f"RMS        : {rms:.6f}"
    )


