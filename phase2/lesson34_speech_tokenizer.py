def calculate_total_stride():

    stride = 1

    for value in STRIDES:

        stride *= value

    return stride


def print_compression_information(
    waveform,
    latent,
):

    waveform_samples = waveform.shape[-1]

    latent_frames = latent.shape[1]

    total_stride = calculate_total_stride()

    waveform_duration = (
        waveform_samples
        / TARGET_SAMPLE_RATE
    )

    latent_rate = (
        latent_frames
        / waveform_duration
    )

    theoretical_rate = (
        TARGET_SAMPLE_RATE
        / total_stride
    )

    compression_ratio = (
        waveform_samples
        / latent_frames
    )

    print("\n")
    print("=" * 72)
    print("TEMPORAL COMPRESSION")
    print("=" * 72)

    print(
        f"\nWaveform samples       : "
        f"{waveform_samples:,}"
    )

    print(
        f"Audio duration         : "
        f"{waveform_duration:.3f} sec"
    )

    print(
        f"Encoder total stride   : "
        f"{total_stride}"
    )

    print(
        f"Latent frames          : "
        f"{latent_frames}"
    )

    print(
        f"Actual latent rate     : "
        f"{latent_rate:.2f} frames/sec"
    )

    print(
        f"Theoretical rate       : "
        f"{theoretical_rate:.2f} frames/sec"
    )

    print(
        f"Waveform/latent ratio  : "
        f"{compression_ratio:.2f}x"
    )

    print(
        "\nInterpretation:"
    )

    print(
        "The encoder replaces thousands of waveform samples "
        "with a much shorter sequence of learned vectors."
    )


