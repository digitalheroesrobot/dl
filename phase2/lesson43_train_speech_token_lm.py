def train(args):

    set_seed(SEED)

    device = torch.device(
        "cuda" if torch.cuda.is_available()
        else "cpu"
    )

    output_dir = Path(
        args.output_dir
    )

    output_dir.mkdir(
        parents=True,
        exist_ok=True,
    )

    print("=" * 72)

    print(
        "LESSON 43 — AUTOREGRESSIVE SPEECH TOKEN LANGUAGE MODEL"
    )

    print("=" * 72)

    print(
        f"\nDevice: {device}"
    )

    if device.type == "cuda":

        print(
            torch.cuda.get_device_name(0)
        )

    print(
        f"Vocabulary: {VOCAB_SIZE}"
    )

    print(
        f"Context length: {args.context_length}"
    )

    print(
        f"Embedding dimension: {D_MODEL}"
    )

    print(
        f"Transformer layers: {NUM_LAYERS}"
    )

    print(
        f"Attention heads: {NUM_HEADS}"
    )

    # --------------------------------------------------------------
    # STEP 1 — LOAD TOKEN DATASET
    # --------------------------------------------------------------

    print("\n" + "=" * 72)

    print("STEP 1 — LOAD SPEECH TOKEN DATASET")

    print("=" * 72)

    train_sequences = load_token_files(
        Path(args.dataset_dir) / "train_tokens"
    )

    val_sequences = load_token_files(
        Path(args.dataset_dir) / "val_tokens"
    )

    # --------------------------------------------------------------
    # STEP 2 — CREATE AUTOREGRESSIVE WINDOWS
    # --------------------------------------------------------------

    print("\n" + "=" * 72)

    print("STEP 2 — CREATE INPUT-TARGET SEQUENCES")

    print("=" * 72)

    train_dataset = SpeechTokenDataset(
        train_sequences,
        args.context_length,
    )

    val_dataset = SpeechTokenDataset(
        val_sequences,
        args.context_length,
    )

    train_loader = DataLoader(
        train_dataset,
        batch_size=args.batch_size,
        shuffle=True,
    )

    val_loader = DataLoader(
        val_dataset,
        batch_size=args.batch_size,
        shuffle=False,
    )

    print(
        f"Training windows: {len(train_dataset)}"
    )

    print(
        f"Validation windows: {len(val_dataset)}"
    )

    # --------------------------------------------------------------
    # STEP 3 — BUILD GPT MODEL
    # --------------------------------------------------------------

    print("\n" + "=" * 72)

    print("STEP 3 — BUILD GPT TRANSFORMER")

    print("=" * 72)

    model = SpeechTokenGPT(
        vocab_size=VOCAB_SIZE,
        context_length=args.context_length,
        d_model=D_MODEL,
        num_heads=NUM_HEADS,
        num_layers=NUM_LAYERS,
        dropout=DROPOUT,
    ).to(device)

    parameter_count = sum(
        p.numel()
        for p in model.parameters()
        if p.requires_grad
    )

    print(
        f"Trainable parameters: {parameter_count:,}"
    )

    # --------------------------------------------------------------
    # STEP 4 — OPTIMIZER
    # --------------------------------------------------------------

    optimizer = torch.optim.AdamW(
        model.parameters(),
        lr=args.learning_rate,
        weight_decay=WEIGHT_DECAY,
    )

    # --------------------------------------------------------------
    # STEP 5 — TRAIN
    # --------------------------------------------------------------

    print("\n" + "=" * 72)

    print("STEP 5 — TRAIN AUTOREGRESSIVE MODEL")

    print("=" * 72)

    history = {

        "train_loss": [],

        "val_loss": [],

        "train_accuracy": [],

        "val_accuracy": [],

    }

    best_val_loss = float("inf")

    best_checkpoint = (
        output_dir / "best_model.pt"
    )

    config = {

        "vocab_size": VOCAB_SIZE,

        "context_length": args.context_length,

        "d_model": D_MODEL,

        "num_heads": NUM_HEADS,

        "num_layers": NUM_LAYERS,

        "dropout": DROPOUT,

        "token_interval_ms": 80,

    }

    for epoch in range(
        1,
        args.epochs + 1,
    ):

        train_metrics = run_epoch(
            model,
            train_loader,
            optimizer,
            device,
            training=True,
        )

        val_metrics = run_epoch(
            model,
            val_loader,
            optimizer,
            device,
            training=False,
        )

        history["train_loss"].append(
            train_metrics["loss"]
        )

        history["val_loss"].append(
            val_metrics["loss"]
        )

        history["train_accuracy"].append(
            train_metrics["accuracy"]
        )

        history["val_accuracy"].append(
            val_metrics["accuracy"]
        )

        # Save best model.
        if val_metrics["loss"] < best_val_loss:

            best_val_loss = val_metrics["loss"]

            save_checkpoint(
                best_checkpoint,
                model,
                optimizer,
                epoch,
                best_val_loss,
                history,
                config,
            )

        if (
            epoch == 1
            or epoch % args.log_interval == 0
            or epoch == args.epochs
        ):

            print(

                f"Epoch {epoch:4d}/{args.epochs} | "

                f"Train Loss "
                f"{train_metrics['loss']:.4f} | "

                f"Val Loss "
                f"{val_metrics['loss']:.4f} | "

                f"Train Acc "
                f"{train_metrics['accuracy']:.3f} | "

                f"Val Acc "
                f"{val_metrics['accuracy']:.3f}"

            )

    # --------------------------------------------------------------
    # STEP 6 — RESTORE BEST CHECKPOINT
    # --------------------------------------------------------------

