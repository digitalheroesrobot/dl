def save_checkpoint(
    path,
    model,
    optimizer,
    epoch,
    best_val_loss,
    history,
    config,
):

    torch.save(
        {

            "model_state_dict": (
                model.state_dict()
            ),

            "optimizer_state_dict": (
                optimizer.state_dict()
            ),

            "epoch": epoch,

            "best_val_loss": best_val_loss,

            "history": history,

            "config": config,

        },
        path,
    )


