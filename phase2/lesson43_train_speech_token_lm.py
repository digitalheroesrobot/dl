# AUTOREGRESSIVE DATASET
# ======================================================================

class SpeechTokenDataset(Dataset):

    """
    Create next-token training examples.

    Example:

        Original:
        [10, 20, 30, 40, 50, 60]

        Input:
        [10, 20, 30, 40, 50]

        Target:
        [20, 30, 40, 50, 60]

    Long recordings are divided into overlapping windows.

    Short recordings are padded.

    Padding targets use -100, which PyTorch's cross-entropy
    ignores during loss calculation.
    """

    def __init__(
        self,
        sequences,
        context_length,
    ):

        self.context_length = context_length

        self.samples = []

        stride = max(
            1,
            context_length // 2,
        )

        for recording in sequences:

            tokens = recording["tokens"]

            starts = range(
                0,
                len(tokens) - 1,
                stride,
            )

            for start in starts:

                segment = tokens[
                    start:start + context_length + 1
                ]

                if len(segment) < 2:

                    continue

                input_tokens = segment[:-1]

                target_tokens = segment[1:]

                valid_length = len(
                    target_tokens
                )

                x = np.zeros(
                    context_length,
                    dtype=np.int64,
                )

                y = np.full(
                    context_length,
                    -100,
                    dtype=np.int64,
                )

                x[:valid_length] = input_tokens

                y[:valid_length] = target_tokens

                self.samples.append(
                    {
                        "input": torch.from_numpy(x),
                        "target": torch.from_numpy(y),
                    }
                )

        if len(self.samples) == 0:

            raise RuntimeError(
                "No autoregressive training samples created."
            )

        print(
            f"Generated training windows: "
            f"{len(self.samples)}"
        )

    def __len__(self):

        return len(self.samples)

    def __getitem__(self, index):

        sample = self.samples[index]

        return (
            sample["input"],
            sample["target"],
        )


# ======================================================================
# CAUSAL SELF-ATTENTION
# ======================================================================

class CausalSelfAttention(nn.Module):

    """
    Multi-head self-attention with causal masking.

    The causal mask prevents position t from accessing
    positions greater than t.

    This ensures genuine autoregressive prediction.
    """

    def __init__(
        self,
        d_model,
        num_heads,
        dropout,
        context_length,
    ):

        super().__init__()

        if d_model % num_heads != 0:

            raise ValueError(
                "d_model must be divisible by num_heads."
            )

        self.d_model = d_model

        self.num_heads = num_heads

        self.head_dim = (
            d_model // num_heads
        )

        self.qkv = nn.Linear(
            d_model,
            3 * d_model,
        )

        self.output_projection = nn.Linear(
            d_model,
            d_model,
        )

        self.attention_dropout = nn.Dropout(
            dropout
        )

        self.residual_dropout = nn.Dropout(
            dropout
        )

        # Upper triangular mask:
        # Future positions receive negative infinity.
        causal_mask = torch.triu(
            torch.full(
                (
                    context_length,
                    context_length,
                ),
                float("-inf"),
            ),
            diagonal=1,
        )

        self.register_buffer(
            "causal_mask",
            causal_mask,
        )

    def forward(self, x):

        batch_size, sequence_length, d_model = (
            x.shape
        )

        # ----------------------------------------------------------
        # STEP 1 — Calculate Q, K and V.
        # ----------------------------------------------------------

        qkv = self.qkv(x)

        qkv = qkv.reshape(
            batch_size,
            sequence_length,
            3,
            self.num_heads,
            self.head_dim,
        )

        qkv = qkv.permute(
            2,
            0,
            3,
            1,
            4,
        )

        q, k, v = qkv.unbind(
            dim=0
        )

        # ----------------------------------------------------------
        # STEP 2 — Scaled dot-product attention.
        # ----------------------------------------------------------

        attention = (
            q @ k.transpose(-2, -1)
        ) / math.sqrt(
            self.head_dim
        )

        # ----------------------------------------------------------
        # STEP 3 — Apply causal mask.
        # ----------------------------------------------------------

        mask = self.causal_mask[
            :sequence_length,
            :sequence_length,
        ]

        attention = attention + mask

        attention = F.softmax(
            attention,
            dim=-1,
        )

        attention = self.attention_dropout(
            attention
        )

        # ----------------------------------------------------------
        # STEP 4 — Combine attention heads.
        # ----------------------------------------------------------

        output = attention @ v

        output = output.transpose(
            1,
            2,
        ).contiguous()

        output = output.reshape(
            batch_size,
            sequence_length,
            d_model,
        )

        output = self.output_projection(
            output
        )

        output = self.residual_dropout(
            output
        )

        return output


# ======================================================================
# TRANSFORMER BLOCK
# ======================================================================

class TransformerBlock(nn.Module):

    def __init__(
        self,
        d_model,
        num_heads,
        dropout,
        context_length,
    ):

        super().__init__()

        self.norm1 = nn.LayerNorm(
            d_model
        )

        self.attention = CausalSelfAttention(
            d_model,
            num_heads,
            dropout,
            context_length,
        )

        self.norm2 = nn.LayerNorm(
            d_model
        )

        self.feed_forward = nn.Sequential(

            nn.Linear(
                d_model,
                4 * d_model,
            ),

            nn.GELU(),

            nn.Linear(
                4 * d_model,
                d_model,
            ),

            nn.Dropout(
                dropout
            ),
        )

    def forward(self, x):

        # Pre-layer normalization.
        x = x + self.attention(
            self.norm1(x)
        )

        x = x + self.feed_forward(
            self.norm2(x)
        )

        return x


# ======================================================================
# GPT-STYLE SPEECH TOKEN LANGUAGE MODEL
# ======================================================================

class SpeechTokenGPT(nn.Module):

    def __init__(
        self,
        vocab_size,
        context_length,
        d_model,
        num_heads,
        num_layers,
        dropout,
    ):

        super().__init__()

        self.vocab_size = vocab_size

        self.context_length = context_length

        # ----------------------------------------------------------
        # STEP 1 — Token embedding.
        # ----------------------------------------------------------

        self.token_embedding = nn.Embedding(
            vocab_size,
            d_model,
        )

        # ----------------------------------------------------------
        # STEP 2 — Positional embedding.
        # ----------------------------------------------------------

        self.position_embedding = nn.Embedding(
            context_length,
            d_model,
        )

        self.embedding_dropout = nn.Dropout(
            dropout
        )

        # ----------------------------------------------------------
        # STEP 3 — Transformer blocks.
        # ----------------------------------------------------------

        self.blocks = nn.ModuleList(

            [
                TransformerBlock(
                    d_model,
                    num_heads,
                    dropout,
                    context_length,
                )
                for _ in range(num_layers)
            ]
        )

        # ----------------------------------------------------------
        # STEP 4 — Final normalization.
        # ----------------------------------------------------------

        self.final_norm = nn.LayerNorm(
            d_model
        )

        # ----------------------------------------------------------
        # STEP 5 — Vocabulary projection.
        # ----------------------------------------------------------

        self.lm_head = nn.Linear(
            d_model,
            vocab_size,
            bias=False,
        )

        # Weight tying.
        self.lm_head.weight = (
            self.token_embedding.weight
        )

        self.apply(
            self._initialize_weights
        )

    @staticmethod
    def _initialize_weights(module):

        if isinstance(
            module,
            nn.Linear,
        ):

            nn.init.normal_(
                module.weight,
                mean=0.0,
                std=0.02,
            )

            if module.bias is not None:

                nn.init.zeros_(
                    module.bias
                )

        elif isinstance(
            module,
            nn.Embedding,
        ):

            nn.init.normal_(
                module.weight,
                mean=0.0,
                std=0.02,
            )

    def forward(self, tokens):

        batch_size, sequence_length = (
            tokens.shape
        )

        if sequence_length > self.context_length:

            raise ValueError(
                "Input exceeds context length."
            )

        positions = torch.arange(
            sequence_length,
            device=tokens.device,
        )

        # Token + positional embeddings.
        x = (
            self.token_embedding(tokens)
            +
            self.position_embedding(positions)
        )

        x = self.embedding_dropout(x)

        # Transformer.
        for block in self.blocks:

            x = block(x)

        x = self.final_norm(x)

        logits = self.lm_head(x)

        return logits


# ======================================================================
# AUTOREGRESSIVE GENERATION
# ======================================================================

@torch.no_grad()
def generate(
    model,
    prompt,
    max_new_tokens,
    temperature=1.0,
    top_k=20,
):

    model.eval()

    generated = prompt.clone()

    for _ in range(max_new_tokens):

        # Keep only the latest context window.
        context = generated[
            :,
            -model.context_length:,
        ]

        logits = model(
            context
        )

        # Last position predicts next token.
        logits = logits[:, -1, :]

        logits = logits / max(
            temperature,
            1e-5,
        )

        # Top-k sampling.
        if top_k is not None:

            k = min(
                top_k,
                logits.shape[-1],
            )

            values, _ = torch.topk(
                logits,
                k,
            )

            threshold = values[
                :,
                [-1],
            ]

            logits = logits.masked_fill(
                logits < threshold,
                float("-inf"),
            )

        probabilities = F.softmax(
            logits,
            dim=-1,
        )

        next_token = torch.multinomial(
            probabilities,
            num_samples=1,
        )

        generated = torch.cat(
            [
                generated,
                next_token,
            ],
            dim=1,
        )

    return generated


# ======================================================================
# TRAINING AND EVALUATION
# ======================================================================

def run_epoch(
    model,
    loader,
    optimizer,
    device,
    training,
):

    if training:

        model.train()

    else:

        model.eval()

    total_loss = 0.0

    total_correct = 0

    total_tokens = 0

    total_batches = 0

    for inputs, targets in loader:

        inputs = inputs.to(
            device
        )

        targets = targets.to(
            device
        )

        if training:

            optimizer.zero_grad(
                set_to_none=True
            )

        with torch.set_grad_enabled(
            training
        ):

            logits = model(
                inputs
            )

            loss = F.cross_entropy(
                logits.reshape(
                    -1,
                    VOCAB_SIZE,
                ),
                targets.reshape(-1),
                ignore_index=-100,
            )

            if training:

                loss.backward()

                torch.nn.utils.clip_grad_norm_(
                    model.parameters(),
                    GRADIENT_CLIP,
                )

                optimizer.step()

        valid = targets != -100

        predictions = logits.argmax(
            dim=-1
        )

        correct = (
            (predictions == targets)
            & valid
        ).sum().item()

        valid_count = valid.sum().item()

        total_correct += correct

        total_tokens += valid_count

        total_loss += loss.item()

        total_batches += 1

    return {

        "loss": (
            total_loss
            / max(total_batches, 1)
        ),

        "accuracy": (
            total_correct
            / max(total_tokens, 1)
        ),

    }


