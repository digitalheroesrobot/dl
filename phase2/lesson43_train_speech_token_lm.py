def load_token_files(directory):

    directory = Path(directory)

    if not directory.exists():

        raise FileNotFoundError(
            f"Token directory not found: {directory}"
        )

    files = sorted(
        directory.glob("*.npy")
    )

    if len(files) == 0:

        raise RuntimeError(
            f"No .npy token files found in {directory}"
        )

    sequences = []

    print(f"\nLoading tokens from {directory}")

    for path in files:

        tokens = np.load(
            path,
            allow_pickle=False,
        )

        tokens = np.asarray(
            tokens,
            dtype=np.int64,
        ).reshape(-1)

        if len(tokens) < 2:

            print(
                f"Skipping {path.name}: "
                "fewer than two tokens."
            )

            continue

        if tokens.min() < 0 or tokens.max() >= VOCAB_SIZE:

            raise ValueError(
                f"Invalid token ID in {path.name}. "
                f"Expected IDs in [0, {VOCAB_SIZE - 1}]."
            )

        sequences.append(
            {
                "name": path.name,
                "tokens": tokens,
            }
        )

        print(
            f"  {path.name}: "
            f"{len(tokens)} tokens | "
            f"{len(np.unique(tokens))} unique"
        )

    if len(sequences) == 0:

        raise RuntimeError(
            f"No usable token sequences in {directory}"
        )

    return sequences


